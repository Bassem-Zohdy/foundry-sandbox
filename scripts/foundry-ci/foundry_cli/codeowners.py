"""Generate a CODEOWNERS file from foundry.json."""
import re
from typing import List

from .config import Config, ConfigError
from .pack_layout import guarded_paths

TECH_LEAD_DOCS = [
    "docs/brd.md", "docs/prd.md", "docs/srs.md", "docs/architecture.md",
    "docs/adr/", "docs/ux/", "docs/test-plan.md", "docs/pdpl-assessment.md",
    "docs/foundry/", "docs/glossary.md", "docs/foundry/gates/",
    # the Discover documents and the PRD addendum ride the G1 gate PR (R28)
    "docs/product-brief.md", "docs/product-brief-addendum.md", "docs/prfaq.md",
    "docs/prfaq-distillate.md", "docs/research/", "docs/prd-addendum.md",
]

# The CI checks run from the base branch and trust its foundry.json (roles,
# riskyPaths) and CODEOWNERS; the workflow file itself comes from the PR; the
# agent guard hooks live in .claude/. A change to any of them needs the tech
# lead's review. Leading slashes anchor the entries to the repo root.
TECH_LEAD_CI = ["/foundry.json", "/.github/", "/.claude/", "scripts/foundry-ci/"]

_OWNER_RE = re.compile(r"^[A-Za-z0-9-]+(/[A-Za-z0-9._-]+)?$")
# CODEOWNERS has no negation, character classes or braces; whitespace and
# control characters would split the owner list or inject lines.
_BAD_PATH_RE = re.compile(r"[\s\x00-\x1f\x7f!\[\]{}]")


def _owner(handle: str, where: str) -> str:
    name = handle[1:] if handle.startswith("@") else handle
    if not _OWNER_RE.match(name):
        raise ConfigError([f"{where}: {handle!r} is not a valid GitHub user or org/team"])
    return "@" + name


def _risky(path: str) -> str:
    if not path or _BAD_PATH_RE.search(path) or path.startswith("#"):
        raise ConfigError([f"riskyPaths: {path!r} cannot be written to CODEOWNERS "
                           "(no whitespace, control characters, ! [ ] { } or leading #)"])
    return path


def build_codeowners(config: Config) -> str:
    """The tech lead owns the product documents, every risky path and each pack's gate files.

    In team mode the tech lead and the developers own everything else (`*`);
    the later, more specific rules win in CODEOWNERS.
    """
    lead = _owner(config.tech_lead, "roles.techLead")
    devs = [_owner(d, "roles.developers") for d in config.developers]
    risky = [_risky(p) for p in config.risky_paths]
    lines: List[str] = ["# Generated by foundry. Later rules take precedence."]
    if config.mode == "team":
        owners = [lead] + [d for d in dict.fromkeys(devs) if d != lead]
        lines.append("* " + " ".join(owners))
    guarded = guarded_paths(config)
    for path in dict.fromkeys(TECH_LEAD_DOCS + TECH_LEAD_CI + guarded + risky):
        lines.append(f"{path} {lead}")
    return "\n".join(lines) + "\n"
